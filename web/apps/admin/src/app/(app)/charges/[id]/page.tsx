import type { AdminSchemas } from "@talksasa/api-client/admin";
import { Amount, CopyButton, DateTime, Status, Table, Td, Th } from "@talksasa/ui";
import type { Metadata } from "next";
import Link from "next/link";
import type { ReactNode } from "react";

import { Facts, PageHeader, Panel } from "@/components/PageHeader";
import { ToneLabel } from "@/components/ToneLabel";
import { api, load } from "@/lib/api";
import { chargeSubjects, chargeTimeline, checkoutURLFrom, txnRole } from "@/lib/charges";
import { CHANNEL, CHARGE_STATUS, KIND } from "@/lib/labels";
import { log } from "@/lib/log";
import { STK_SOURCE, stkResult, stkStatus } from "@/lib/mpesa";
import { prettyJSON } from "@/lib/webhooks";

export const metadata: Metadata = { title: "Charge" };

type Delivery = AdminSchemas["WebhookDelivery"];

const link = "text-violet hover:underline";
/** How many of the app's recent deliveries are searched for this charge's events. */
const DELIVERY_WINDOW = 200;

/**
 * Webhook deliveries about this charge, its prompts and its transactions,
 * found among the app's most recent deliveries, plus a checkout link read
 * from the newest charge event body. Best effort: the page still renders if
 * this fails.
 */
async function webhookEvents(appId: string, subjects: Set<string>): Promise<{ items: Delivery[]; checkoutURL?: string } | null> {
  try {
    const c = await api();
    const { data } = await c.GET("/webhook-deliveries", { params: { query: { app_id: appId, limit: DELIVERY_WINDOW } } });
    const items = (data?.items ?? []).filter((d) => subjects.has(d.subject_id));
    const latestChargeEvent = items.find((d) => d.subject_type === "charge");
    let checkoutURL: string | undefined;
    if (latestChargeEvent) {
      const ev = await c.GET("/webhook-deliveries/{eventID}", { params: { path: { eventID: latestChargeEvent.event_id } } });
      checkoutURL = checkoutURLFrom(ev.data?.event.data);
    }
    return { items, checkoutURL };
  } catch (e) {
    log.error({ err: e instanceof Error ? e.message : String(e) }, "could not list webhook events for a charge");
    return null;
  }
}

export default async function ChargePage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const c = await load((cl) => cl.GET("/charges/{id}", { params: { path: { id } } }));
  const events = await webhookEvents(c.app_id, chargeSubjects(c));
  // Prefer a checkout_url on the charge itself if the admin API adds one.
  const checkoutURL = (c as { checkout_url?: string }).checkout_url ?? events?.checkoutURL;
  const timeline = chargeTimeline(c);
  const live = c.status === "pending" || c.status === "needs_review";

  return (
    <>
      <PageHeader
        back={
          <Link href="/charges" className={link}>
            Charges
          </Link>
        }
        title={
          <>
            <Amount value={c.amount} /> <span className="text-muted">for {c.reference}</span>
          </>
        }
        lead={c.description ?? CHARGE_STATUS[c.status]?.help}
        actions={<Status value={c.status} className="text-sm" />}
      />
      <div className="grid gap-6">
        {c.app_status !== "active" ? (
          <Panel>
            <p className="text-sm text-ink-2">
              <span className="font-medium text-warn">{c.app_name} is suspended.</span> Its API keys and checkout links do not work.
              Money that still arrives is recorded and forwarded.
            </p>
          </Panel>
        ) : null}

        <Panel title="Details">
          <Facts
            items={[
              [
                "App",
                <Link key="a" href={`/apps/${c.app_id}`} className={link}>
                  {c.app_name} ({c.account_prefix})
                </Link>,
              ],
              ["Reference", <span key="r" className="font-medium">{c.reference}</span>],
              [
                "Account number",
                <span key="n">
                  <span className="font-mono text-[0.8125rem]">{c.account_number}</span>
                  <span className="block text-[0.75rem] text-muted">{c.account_generated ? "Generated by the gateway" : "Given by the app"}</span>
                </span>,
              ],
              ["Status", CHARGE_STATUS[c.status]?.help ?? c.status],
              ["Phone", c.phone ?? "—"],
              [
                "Paid by",
                c.transaction_id ? (
                  <Link key="p" href={`/transactions/${c.transaction_id}`} className={link}>
                    View payment
                  </Link>
                ) : (
                  "Not paid yet"
                ),
              ],
              ["Created", <DateTime key="c" value={c.created_at} />],
              [c.status === "pending" ? "Expires" : "Expiry", <DateTime key="e" value={c.expires_at} />],
              ["Paid", <DateTime key="s" value={c.succeeded_at} fallback="Not yet" />],
              ...(c.closed_at ? ([[c.status === "cancelled" ? "Cancelled" : "Closed", <DateTime key="cl" value={c.closed_at} />]] as Array<[string, ReactNode]>) : []),
              ["Charge id", <span key="i" className="font-mono text-[0.8125rem]">{c.id}</span>],
            ]}
          />
        </Panel>

        <Panel title="Checkout link">
          {checkoutURL ? (
            <div className="flex flex-wrap items-center gap-3">
              <a href={checkoutURL} target="_blank" rel="noopener noreferrer" className={`${link} min-w-0 font-mono text-[0.8125rem] break-all`}>
                {checkoutURL}
              </a>
              <CopyButton value={checkoutURL} label="Copy" />
            </div>
          ) : (
            <p className="text-sm text-muted">The app received this charge’s checkout link when it created it; it is in the app’s API response and webhook events.</p>
          )}
          <p className="mt-2 text-[0.8125rem] text-muted">
            {live
              ? "Anyone with the link can see the amount and pay it. Don’t post it publicly."
              : "The link now shows the customer the charge’s final state; it can no longer be paid."}
          </p>
        </Panel>

        <Panel title="Timeline">
          <ol className="grid gap-3">
            {timeline.map((e, i) => (
              <li key={i} className="flex flex-wrap items-baseline gap-x-3 text-sm">
                <DateTime value={e.at} />
                {e.href ? (
                  <Link href={e.href} className="hover:underline">
                    <ToneLabel label={e.label} tone={e.tone} />
                  </Link>
                ) : (
                  <ToneLabel label={e.label} tone={e.tone} />
                )}
                {e.detail ? <span className="text-muted">{e.detail}</span> : null}
              </li>
            ))}
          </ol>
        </Panel>

        <Panel title="Transactions" flush>
          {c.transactions.length === 0 ? (
            <p className="p-5 text-sm text-muted">No money has moved for this charge yet.</p>
          ) : (
            <Table label="Transactions for this charge">
              <thead>
                <tr>
                  <Th>When</Th>
                  <Th>What</Th>
                  <Th>Receipt</Th>
                  <Th>How</Th>
                  <Th>Status</Th>
                  <Th align="right">Amount</Th>
                </tr>
              </thead>
              <tbody>
                {c.transactions.map((t) => {
                  const role = txnRole(t, c.transaction_id);
                  return (
                    <tr key={t.id} className="hover:bg-wash/60">
                      <Td>
                        <Link href={`/transactions/${t.id}`} className="text-ink hover:text-violet hover:underline">
                          <DateTime value={t.created_at} />
                        </Link>
                      </Td>
                      <Td>
                        <ToneLabel label={role.label} tone={role.tone} />
                      </Td>
                      <Td className="font-mono text-[0.8125rem]">{t.receipt ?? <span className="text-faint">—</span>}</Td>
                      <Td className="text-ink-2">{t.kind === "payment" ? (CHANNEL[t.channel] ?? t.channel) : (KIND[t.kind] ?? t.kind)}</Td>
                      <Td>
                        <Status value={t.status} />
                      </Td>
                      <Td align="right">
                        <Amount value={t.direction === "out" ? -t.amount : t.amount} className={t.direction === "out" ? "text-bad" : undefined} />
                      </Td>
                    </tr>
                  );
                })}
              </tbody>
            </Table>
          )}
        </Panel>

        <Panel title="Payment prompts" flush>
          {c.stk_pushes.length === 0 ? (
            <p className="p-5 text-sm text-muted">No M-Pesa prompts have been sent for this charge.</p>
          ) : (
            <Table label="M-Pesa payment prompts for this charge">
              <thead>
                <tr>
                  <Th>Sent</Th>
                  <Th>From</Th>
                  <Th>Phone</Th>
                  <Th>Status</Th>
                  <Th>Result</Th>
                  <Th align="right">Amount</Th>
                </tr>
              </thead>
              <tbody>
                {c.stk_pushes.map((p) => {
                  const s = stkStatus(p.status);
                  const result = stkResult(p);
                  return (
                    <tr key={p.id}>
                      <Td>
                        <Link href={`/transactions/${p.paid_transaction_id ?? p.transaction_id}`} className="text-ink hover:text-violet hover:underline">
                          <DateTime value={p.created_at} />
                        </Link>
                      </Td>
                      <Td className="text-ink-2">{STK_SOURCE[p.source] ?? p.source}</Td>
                      <Td className="font-mono text-[0.8125rem]">{p.phone}</Td>
                      <Td>
                        <ToneLabel label={s.label} tone={s.tone} />
                        {p.query_attempts > 0 ? (
                          <span className="block text-[0.75rem] text-muted">
                            Checked with Safaricom {p.query_attempts} {p.query_attempts === 1 ? "time" : "times"}
                          </span>
                        ) : null}
                      </Td>
                      <Td className="max-w-72 text-[0.8125rem] text-ink-2">
                        {result ?? <span className="text-faint">—</span>}
                        {p.checkout_request_id ? (
                          <span className="block truncate font-mono text-[0.75rem] text-muted" title={p.checkout_request_id}>
                            {p.checkout_request_id}
                          </span>
                        ) : null}
                      </Td>
                      <Td align="right">
                        <Amount value={p.amount} />
                      </Td>
                    </tr>
                  );
                })}
              </tbody>
            </Table>
          )}
        </Panel>

        <Panel title="Webhook events" flush>
          {events === null ? (
            <p className="p-5 text-sm text-muted">Webhook events couldn’t be loaded. Reload the page to try again.</p>
          ) : events.items.length === 0 ? (
            <p className="p-5 text-sm text-muted">
              No webhook events for this charge among {c.app_name}’s latest {DELIVERY_WINDOW} deliveries.{" "}
              <Link href={`/webhooks?app_id=${c.app_id}`} className={link}>
                All of {c.app_name}’s deliveries
              </Link>
            </p>
          ) : (
            <Table label="Webhook events for this charge">
              <thead>
                <tr>
                  <Th>Created</Th>
                  <Th>Event</Th>
                  <Th>Status</Th>
                  <Th align="right">Attempts</Th>
                </tr>
              </thead>
              <tbody>
                {events.items.map((d) => (
                  <tr key={d.event_id} className="hover:bg-wash/60">
                    <Td>
                      <Link href={`/webhooks/${d.event_id}`} className="text-ink hover:text-violet hover:underline">
                        <DateTime value={d.created_at} />
                      </Link>
                    </Td>
                    <Td className="font-mono text-[0.8125rem]">{d.event_type}</Td>
                    <Td>
                      <Status value={d.status} />
                    </Td>
                    <Td align="right" className="num">
                      {d.attempts}
                    </Td>
                  </tr>
                ))}
              </tbody>
            </Table>
          )}
        </Panel>

        <Panel title="Metadata">
          {c.metadata && Object.keys(c.metadata).length > 0 ? (
            <>
              <p className="mb-3 text-[0.8125rem] text-muted">Set by the app and echoed back to it unchanged.</p>
              <pre className="overflow-x-auto rounded-md bg-wash p-4 font-mono text-[0.75rem] leading-relaxed text-ink-2">{prettyJSON(c.metadata)}</pre>
            </>
          ) : (
            <p className="text-sm text-muted">The app set no metadata.</p>
          )}
        </Panel>

        <p className="text-[0.8125rem] text-muted">
          <Link href={`/transactions?charge_id=${c.id}`} className={link}>
            Search transactions for this charge
          </Link>
        </p>
      </div>
    </>
  );
}
